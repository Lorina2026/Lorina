-- ════════════════════════════════════════════════════════════════
--
--  【怎么用】
--   1. 打开 https://supabase.com 注册并登录（邮箱即可，免费）
--   2. New project → 填项目名（如 haigui）→ 设置数据库密码 → 选区域
--      区域建议选 Singapore（新加坡），国内访问最快
--   3. 等 1~2 分钟项目初始化完成
--   4. 左侧菜单点 SQL Editor → New query
--   5. 把本文件【全部内容】复制粘贴进去 → 点右下角 Run
--   6. 看到 "Success. No rows returned" 就是建好了
--
--  本脚本可以重复运行，不会重复建表、也不会报错。
-- ════════════════════════════════════════════════════════════════


-- ────────────────────────────────────────────────────────────────
-- 一、投票表
--     设计成"每台设备一行"，而不是"每投一票加一次数"。
--     好处：① 同一台设备重复投不会刷票，只会改投
--           ② 不会出现两个人同时投票把计数写错的情况
-- ────────────────────────────────────────────────────────────────
create table if not exists public.votes (
  voter_id   text        primary key,                             -- 浏览器本地生成的设备标识
  choice     smallint    not null check (choice between 1 and 4), -- 1=图一 2=图二 3=图三 4=图四
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);


-- ────────────────────────────────────────────────────────────────
-- 二、留言表
--     name / content 都加了长度校验，防止空提交和超长内容
-- ────────────────────────────────────────────────────────────────
create table if not exists public.messages (
  id         bigint      generated by default as identity primary key,
  name       text        not null check (char_length(btrim(name))    between 1 and 20),
  content    text        not null check (char_length(btrim(content)) between 1 and 500),
  created_at timestamptz not null default now()
);

-- 按时间倒序取最新留言，加个索引
create index if not exists messages_created_at_idx
  on public.messages (created_at desc);


-- ────────────────────────────────────────────────────────────────
-- 三、打开行级安全（RLS）
--     不打开的话，Supabase 会提示表暴露在公网
-- ────────────────────────────────────────────────────────────────
alter table public.votes    enable row level security;
alter table public.messages enable row level security;


-- ────────────────────────────────────────────────────────────────
-- 四、访问策略
--
--  这是课堂场景，策略开成"所有人可读写"，让同学用手机匿名就能参与。
--  ⚠️ 代价：理论上任何拿到网址的人都能删留言。课堂用完全够，
--     课后想收紧就把 messages_delete 这条策略 drop 掉即可（见文件末尾）。
-- ────────────────────────────────────────────────────────────────

-- 投票：所有人可读 / 可投 / 可改投
drop policy if exists votes_read   on public.votes;
drop policy if exists votes_insert on public.votes;
drop policy if exists votes_update on public.votes;

create policy votes_read   on public.votes for select using (true);
create policy votes_insert on public.votes for insert with check (true);
create policy votes_update on public.votes for update using (true) with check (true);

-- 留言：所有人可读 / 可发 / 可删（"清空全部留言"按钮需要 delete 权限）
drop policy if exists messages_read   on public.messages;
drop policy if exists messages_insert on public.messages;
drop policy if exists messages_delete on public.messages;

create policy messages_read   on public.messages for select using (true);
create policy messages_insert on public.messages for insert with check (true);
create policy messages_delete on public.messages for delete using (true);


-- ────────────────────────────────────────────────────────────────
-- 五、表级授权
--     少数新项目的默认权限较严，加上这几句可以避免
--     "permission denied for table votes" 这类报错
-- ────────────────────────────────────────────────────────────────
grant usage on schema public to anon, authenticated;
grant select, insert, update on public.votes    to anon, authenticated;
grant select, insert, delete on public.messages to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;


-- ────────────────────────────────────────────────────────────────
-- 六、开启 Realtime 实时推送
--     这一句是"全班手机立刻同步"的关键
-- ────────────────────────────────────────────────────────────────
do $$
begin
  begin
    alter publication supabase_realtime add table public.votes;
  exception when duplicate_object then null;   -- 已经加过就跳过
  end;
  begin
    alter publication supabase_realtime add table public.messages;
  exception when duplicate_object then null;
  end;
end $$;

-- 让"删除"事件也带上完整旧数据：
-- 点【清空全部留言】时，所有同学的屏幕才会一起把列表清空
alter table public.messages replica identity full;
alter table public.votes    replica identity full;


-- ────────────────────────────────────────────────────────────────
-- 七、自检：运行后应该看到两张表，行数都是 0
-- ────────────────────────────────────────────────────────────────
select 'votes'    as "表名", count(*) as "当前行数" from public.votes
union all
select 'messages' as "表名", count(*) as "当前行数" from public.messages;


